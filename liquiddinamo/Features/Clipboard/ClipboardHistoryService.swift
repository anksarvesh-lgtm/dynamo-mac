//
//  ClipboardHistoryService.swift
//  LiquidDynamo
//
//  Service managing privacy-first clipboard history supporting Text, Images, Files, and URLs.
//

import AppKit
import Defaults
import Foundation

@MainActor
public final class ClipboardHistoryService: ObservableObject {
    public static let shared = ClipboardHistoryService()

    @Published public private(set) var recentEntries: [ClipboardEntry] = []
    @Published public private(set) var pinnedEntries: [ClipboardEntry] = []
    @Published public private(set) var isScreenCaptured: Bool = false
    @Published public private(set) var accessDenied: Bool = false

    private var lastChangeCount: Int = -1
    private var checkTimer: Timer?
    private var isSampling: Bool = false

    /// Password manager bundle IDs excluded by default
    private let excludedBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop",
        "com.dashlane.Dashlane",
        "com.apple.keychainaccess"
    ]

    /// Concealed pasteboard types used by password managers and sensitive fields
    private let concealedTypeIdentifiers: [String] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.sorman.PasteboardTypePassword",
        "com.typeit4me.clipping",
        "Pasteboard generator type"
    ]

    private var pinnedFileURL: URL {
        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let dir = appSupport.appendingPathComponent("LiquidDynamo", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("pinned_clipboard.json")
    }

    private var recentFileURL: URL {
        let appSupport = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        let dir = appSupport.appendingPathComponent("LiquidDynamo", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("recent_clipboard.json")
    }

    private init() {
        self.lastChangeCount = -1
        loadPinnedEntries()
        loadRecentEntries()
    }

    // MARK: - Lifecycle (Continuously active background monitor)

    public func start() {
        guard Defaults[.showDashboardClipboard] else { return }
        guard !isSampling else { return }
        isSampling = true

        updateScreenCaptureState()
        checkPasteboard()

        checkTimer?.invalidate()
        // 0.35s interval provides instant real-time capture with zero CPU overhead
        checkTimer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
    }

    public func stop() {
        isSampling = false
        checkTimer?.invalidate()
        checkTimer = nil
    }

    public func openPrivacySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard"),
           NSWorkspace.shared.open(url) {
            return
        }
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security") {
            NSWorkspace.shared.open(url)
        }
    }

    // MARK: - Screen Capture Detection

    public func updateScreenCaptureState() {
        // Use HardwareSensorMonitor's verified WindowServer query (screencaptured, replayd)
        // rather than guessing solely from background bundle IDs of apps like Teams or Zoom.
        let isCaptured = HardwareSensorMonitor.shared.isScreenRecordingActive
        if self.isScreenCaptured != isCaptured {
            self.isScreenCaptured = isCaptured
        }
    }

    // MARK: - Pasteboard Checking

    public func checkPasteboard() {
        guard Defaults[.showDashboardClipboard] else { return }
        let pb = NSPasteboard.general
        let currentCount = pb.changeCount
        guard currentCount != lastChangeCount else { return }
        let isInitialCheck = (lastChangeCount == -1)
        lastChangeCount = currentCount

        updateScreenCaptureState()

        // 1. Exclude password managers
        if let frontApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier {
            if excludedBundleIDs.contains(frontApp) {
                return
            }
        }

        // 2. Exclude concealed/sensitive types
        guard let types = pb.types else { return }
        for type in types {
            let identifier = type.rawValue
            for concealed in concealedTypeIdentifiers {
                if identifier.localizedCaseInsensitiveContains(concealed) {
                    return
                }
            }
        }

        // 3. Shield contents during active screen recording
        if isScreenCaptured {
            return
        }

        // --- Multi-Type Pasteboard Extraction ---

        // A. Check for Files
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [NSPasteboard.ReadingOptionKey.urlReadingFileURLsOnly: true]) as? [URL],
           let firstURL = urls.first, firstURL.isFileURL {
            let name = firstURL.lastPathComponent
            let entry = ClipboardEntry(
                type: .file,
                text: name,
                fileURL: firstURL,
                imageData: nil,
                timestamp: Date(),
                isPinned: false
            )
            addOrPromoteEntry(entry, isInitialCheck: isInitialCheck)
            return
        }

        // B. Check for Images (TIFF / PNG / JPEG)
        if types.contains(.tiff) || types.contains(.png) {
            if let imgData = pb.data(forType: .png) ?? pb.data(forType: .tiff),
               let image = NSImage(data: imgData) {
                let thumbData = compressedImageData(from: image) ?? imgData
                let desc = "Image (\(Int(image.size.width)) × \(Int(image.size.height)))"
                let entry = ClipboardEntry(
                    type: .image,
                    text: desc,
                    fileURL: nil,
                    imageData: thumbData,
                    timestamp: Date(),
                    isPinned: false
                )
                addOrPromoteEntry(entry, isInitialCheck: isInitialCheck)
                return
            }
        }

        // C. Check for URLs
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           let firstURL = urls.first, !firstURL.isFileURL,
           let scheme = firstURL.scheme?.lowercased(), (scheme == "http" || scheme == "https") {
            let entry = ClipboardEntry(
                type: .url,
                text: firstURL.absoluteString,
                fileURL: nil,
                imageData: nil,
                timestamp: Date(),
                isPinned: false
            )
            addOrPromoteEntry(entry, isInitialCheck: isInitialCheck)
            return
        }

        // D. Check for Text (also detect if raw string is a URL)
        if types.contains(.string), let string = pb.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }

            if let url = URL(string: trimmed),
               let scheme = url.scheme?.lowercased(),
               (scheme == "http" || scheme == "https"),
               url.host != nil {
                let entry = ClipboardEntry(
                    type: .url,
                    text: trimmed,
                    fileURL: nil,
                    imageData: nil,
                    timestamp: Date(),
                    isPinned: false
                )
                addOrPromoteEntry(entry, isInitialCheck: isInitialCheck)
            } else {
                let entry = ClipboardEntry(
                    type: .text,
                    text: string,
                    fileURL: nil,
                    imageData: nil,
                    timestamp: Date(),
                    isPinned: false
                )
                addOrPromoteEntry(entry, isInitialCheck: isInitialCheck)
            }
            return
        }
    }

    private func addOrPromoteEntry(_ entry: ClipboardEntry, isInitialCheck: Bool) {
        // 1. If identical item is already pinned, do not add duplicate to recent
        if pinnedEntries.contains(where: { isIdentical($0, entry) }) {
            return
        }

        // 2. Remove duplicate from recentEntries if present (promote to top)
        recentEntries.removeAll(where: { isIdentical($0, entry) })

        // 3. Insert at top
        recentEntries.insert(entry, at: 0)

        // 4. Retain up to 25 recent clipboard items (matches product requirement)
        if recentEntries.count > 25 {
            recentEntries.removeLast(recentEntries.count - 25)
        }
        saveRecentEntries()

        // 5. Fire Bug 2 clipboard-copied capsule exactly once per new copy
        if !isInitialCheck {
            DynamicIslandHub.shared.triggerClipboardAlert(text: entry.previewText)
        }
    }

    private func isIdentical(_ a: ClipboardEntry, _ b: ClipboardEntry) -> Bool {
        if a.type != b.type { return false }
        switch a.type {
        case .file:
            return a.fileURL?.standardizedFileURL.path == b.fileURL?.standardizedFileURL.path
        case .image:
            if let dataA = a.imageData, let dataB = b.imageData {
                return dataA.prefix(256) == dataB.prefix(256)
            }
            return false
        case .url:
            return a.text.trimmingCharacters(in: .whitespacesAndNewlines) == b.text.trimmingCharacters(in: .whitespacesAndNewlines)
        case .text:
            return a.text == b.text
        }
    }

    private func compressedImageData(from image: NSImage) -> Data? {
        let maxDimension: CGFloat = 500
        var newSize = image.size
        if newSize.width > maxDimension || newSize.height > maxDimension {
            let aspect = newSize.width / newSize.height
            if aspect > 1 {
                newSize = CGSize(width: maxDimension, height: maxDimension / aspect)
            } else {
                newSize = CGSize(width: maxDimension * aspect, height: maxDimension)
            }
        }

        let newImage = NSImage(size: newSize)
        newImage.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: newSize), from: NSRect(origin: .zero, size: image.size), operation: .copy, fraction: 1.0)
        newImage.unlockFocus()

        guard let tiff = newImage.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else {
            return image.tiffRepresentation
        }
        return rep.representation(using: .jpeg, properties: [.compressionFactor: 0.85]) ?? image.tiffRepresentation
    }

    // MARK: - Actions

    public func copyToPasteboard(_ entry: ClipboardEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()

        switch entry.type {
        case .file:
            if let fileURL = entry.fileURL {
                pb.writeObjects([fileURL as NSURL])
                pb.setString(fileURL.path, forType: .string)
            } else if FileManager.default.fileExists(atPath: entry.text) {
                let url = URL(fileURLWithPath: entry.text)
                pb.writeObjects([url as NSURL])
                pb.setString(url.path, forType: .string)
            }
        case .image:
            if let data = entry.imageData, let img = NSImage(data: data) {
                if let tiff = img.tiffRepresentation {
                    pb.setData(tiff, forType: .tiff)
                }
                pb.setData(data, forType: .png)
            }
        case .url:
            if let url = URL(string: entry.text) {
                pb.writeObjects([url as NSURL])
                pb.setString(entry.text, forType: .string)
            } else {
                pb.setString(entry.text, forType: .string)
            }
        case .text:
            pb.setString(entry.text, forType: .string)
        }

        // Update change counter so we don't re-ingest our own copy
        self.lastChangeCount = pb.changeCount
    }

    public func togglePin(_ entry: ClipboardEntry) {
        if entry.isPinned {
            if let idx = pinnedEntries.firstIndex(where: { $0.id == entry.id }) {
                var item = pinnedEntries.remove(at: idx)
                item.isPinned = false
                savePinnedEntries()
                recentEntries.insert(item, at: 0)
                if recentEntries.count > 25 {
                    recentEntries.removeLast(recentEntries.count - 25)
                }
                saveRecentEntries()
            }
        } else {
            if let idx = recentEntries.firstIndex(where: { $0.id == entry.id }) {
                var item = recentEntries.remove(at: idx)
                item.isPinned = true
                saveRecentEntries()
                pinnedEntries.insert(item, at: 0)
                savePinnedEntries()
            }
        }
    }

    public func remove(_ entry: ClipboardEntry) {
        recentEntries.removeAll { $0.id == entry.id }
        saveRecentEntries()
        if pinnedEntries.contains(where: { $0.id == entry.id }) {
            pinnedEntries.removeAll { $0.id == entry.id }
            savePinnedEntries()
        }
    }

    public func clearHistory() {
        recentEntries.removeAll()
        saveRecentEntries()
    }

    // MARK: - Persistence (Pinned and Recent entries)

    private func savePinnedEntries() {
        do {
            let data = try JSONEncoder().encode(pinnedEntries)
            try data.write(to: pinnedFileURL, options: .atomic)
        } catch {
            print("❌ Failed to save pinned clipboard entries: \(error)")
        }
    }

    private func loadPinnedEntries() {
        guard FileManager.default.fileExists(atPath: pinnedFileURL.path) else { return }
        do {
            let data = try Data(contentsOf: pinnedFileURL)
            self.pinnedEntries = try JSONDecoder().decode([ClipboardEntry].self, from: data)
        } catch {
            print("⚠️ Failed to load pinned clipboard entries: \(error)")
        }
    }

    private func saveRecentEntries() {
        do {
            let data = try JSONEncoder().encode(recentEntries)
            try data.write(to: recentFileURL, options: .atomic)
        } catch {
            print("❌ Failed to save recent clipboard entries: \(error)")
        }
    }

    private func loadRecentEntries() {
        guard FileManager.default.fileExists(atPath: recentFileURL.path) else { return }
        do {
            let data = try Data(contentsOf: recentFileURL)
            self.recentEntries = try JSONDecoder().decode([ClipboardEntry].self, from: data)
        } catch {
            print("⚠️ Failed to load recent clipboard entries: \(error)")
        }
    }
}
