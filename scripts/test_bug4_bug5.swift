import Foundation
import AppKit

// MARK: - Mock Color Dropper Record for verification
struct TestColorRecord {
    let hex: String
    let red: Double
    let green: Double
    let blue: Double
    let alpha: Double

    var rgbString: String {
        let r = Int(round(red * 255))
        let g = Int(round(green * 255))
        let b = Int(round(blue * 255))
        return "rgb(\(r), \(g), \(b))"
    }

    var hslString: String {
        let r = red
        let g = green
        let b = blue
        let maxVal = max(r, g, b)
        let minVal = min(r, g, b)
        let delta = maxVal - minVal

        var h: Double = 0
        var s: Double = 0
        let l: Double = (maxVal + minVal) / 2.0

        if delta > 0.00001 {
            s = l > 0.5 ? delta / (2.0 - maxVal - minVal) : delta / (maxVal + minVal)
            if maxVal == r {
                h = ((g - b) / delta).truncatingRemainder(dividingBy: 6)
            } else if maxVal == g {
                h = ((b - r) / delta) + 2.0
            } else {
                h = ((r - g) / delta) + 4.0
            }
            h *= 60.0
            if h < 0 { h += 360.0 }
        }

        let hInt = Int(round(h))
        let sInt = Int(round(s * 100))
        let lInt = Int(round(l * 100))
        return "hsl(\(hInt), \(sInt)%, \(lInt)%)"
    }

    var isLight: Bool {
        let lum = 0.2126 * red + 0.7152 * green + 0.0722 * blue
        return lum > 0.55
    }
}

// 1. Verify Color Calculations
print("=== Testing Color Calculations ===")
// Pure Red
let pureRed = TestColorRecord(hex: "#FF0000", red: 1.0, green: 0.0, blue: 0.0, alpha: 1.0)
assert(pureRed.rgbString == "rgb(255, 0, 0)", "RGB calculation mismatch: \(pureRed.rgbString)")
assert(pureRed.hslString == "hsl(0, 100%, 50%)", "HSL calculation mismatch: \(pureRed.hslString)")
assert(!pureRed.isLight, "Red should not be light")
print("✅ Pure Red Passed: RGB=\(pureRed.rgbString), HSL=\(pureRed.hslString)")

// Pure White
let pureWhite = TestColorRecord(hex: "#FFFFFF", red: 1.0, green: 1.0, blue: 1.0, alpha: 1.0)
assert(pureWhite.rgbString == "rgb(255, 255, 255)")
assert(pureWhite.hslString == "hsl(0, 0%, 100%)", "HSL white: \(pureWhite.hslString)")
assert(pureWhite.isLight, "White must be light")
print("✅ Pure White Passed: RGB=\(pureWhite.rgbString), HSL=\(pureWhite.hslString)")

// Apple Blue #007AFF
let appleBlue = TestColorRecord(hex: "#007AFF", red: 0.0, green: 0.4784, blue: 1.0, alpha: 1.0)
assert(appleBlue.rgbString == "rgb(0, 122, 255)")
assert(appleBlue.hslString == "hsl(211, 100%, 50%)", "Apple Blue HSL: \(appleBlue.hslString)")
print("✅ Apple Blue Passed: RGB=\(appleBlue.rgbString), HSL=\(appleBlue.hslString)")

// 2. Verify Concealed Pasteboard Types
print("\n=== Testing Concealed Pasteboard Types Filtering ===")
let concealedTypes = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.sorman.PasteboardTypePassword"
]

func shouldFilterOut(type: String) -> Bool {
    for concealed in concealedTypes {
        if type.localizedCaseInsensitiveContains(concealed) {
            return true
        }
    }
    return false
}

assert(shouldFilterOut(type: "org.nspasteboard.ConcealedType") == true)
assert(shouldFilterOut(type: "com.agilebits.onepassword") == true)
assert(shouldFilterOut(type: "public.utf8-plain-text") == false)
assert(shouldFilterOut(type: "public.png") == false)
print("✅ Concealed Types Filtering Passed")

print("\n🎉 ALL BUG 4 & BUG 5 TESTS PASSED SUCCESSFULLY!")
