import AppKit
import IslandCore

/// Optional, local-only clipboard confirmation ("Copied …"). macOS offers no pasteboard change
/// notification, so this checks `changeCount` once per second — only while the user has it enabled.
/// Content is never stored or sent anywhere; password managers' concealed items are ignored.
@MainActor
final class ClipboardProvider {
    private let sink: (ActivityUpdate) -> Void
    private var task: Task<Void, Never>?
    private var lastCount = NSPasteboard.general.changeCount
    static let ignoredTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(sink: @escaping (ActivityUpdate) -> Void) { self.sink = sink }

    func start() {
        guard task == nil else { return }
        lastCount = NSPasteboard.general.changeCount
        task = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(nanoseconds: 1_000_000_000)
                self?.check()
            }
        }
    }

    func stop() {
        task?.cancel()
        task = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = pb.types?.map(\.rawValue) ?? []
        guard !types.contains(where: Self.ignoredTypes.contains) else { return }
        let preview: String, kind: String
        if let s = pb.string(forType: .string), !s.isEmpty {
            preview = String(s.prefix(80)); kind = "Text"
        } else if pb.canReadObject(forClasses: [NSImage.self], options: nil) {
            preview = "Image"; kind = "Image"
        } else if let urls = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], let u = urls.first {
            preview = u.lastPathComponent; kind = "File"
        } else { return }
        sink(.upsert(Activity(id: "clipboard", kind: .clipboard, priority: .normal,
                              content: .clipboard(ClipboardActivity(preview: preview, typeDescription: kind)),
                              expiresAt: Date().addingTimeInterval(2.5))))
    }
}
